export const getCategory = (id) => CATEGORIES.find((c) => c.id === id);
export const signatureOf = (category) => category.models.find((m) => m.id === category.signature) || category.models[0];
export const getModel = (categoryId, modelId) => getCategory(categoryId)?.models.find((m) => m.id === modelId);

export function partMeta(category, model, key) {
  return { label: key, info: '', ...(category.partInfo[key] || {}), ...((model.partInfo || {})[key] || {}) };
}

export function formatPrice(n) {
  return new Intl.NumberFormat(BRAND.locale, { style: 'currency', currency: BRAND.currency, maximumFractionDigits: 0 }).format(n);
}
